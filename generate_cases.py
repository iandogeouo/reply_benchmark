def write_csv(path, rows):
    with open(path, "w", newline="", encoding="utf-8-sig") as f:
        writer = csv.writer(f)
        writer.writerow(HEADER)
        for r in rows:
            writer.writerow([r["陳情"], r["公務員"], r["擬答"], "", r.get("反面", "")])
    print(f"OK {path} ({len(rows)})")


